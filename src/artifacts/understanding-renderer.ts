import type { ValidationIssue } from "./artifact-types.ts";

/**
 * Deterministic Markdown renderer for the understanding phase.
 *
 * understanding.json (the validated canonical artifact) is the single source
 * of truth; understanding.md is a fixed-structure projection rendered by this
 * module ONLY. The phase LLM never composes or edits the Markdown. Rendering
 * the same validated JSON with the same renderer version always produces the
 * same Markdown — no LLM call is involved, so re-rendering is a recovery
 * path, not a re-interpretation.
 *
 * Untrusted content (the original prompt and LLM-supplied free text) is
 * neutralized so it cannot inject or replace the document's required
 * structure: the prompt is emitted inside a backtick fence sized above any
 * backtick run in the content, and free-text lines that would parse as
 * headings have their leading '#' characters stripped.
 */

export const UNDERSTANDING_RENDERER_VERSION = "1.0.0";

export const UNDERSTANDING_TITLE = "# Understanding";

/** The fixed heading structure, in the exact required order. */
export const UNDERSTANDING_HEADINGS: readonly string[] = [
  "## 1. Metadata",
  "## 2. Original Prompt",
  "## 3. Interpreted Intent",
  "## 4. Explicit Information",
  "## 5. Inferences and Assumptions",
  "## 6. Scope and Boundaries",
  "## 7. Ambiguities and Open Questions",
  "## 8. Candidate Requirements",
  "## 9. Understanding Summary",
  "## 10. Traceability",
];

/* ------------------------------------------------------------------ *
 * The canonical document shape (mirrors understanding.schema.json).
 * ------------------------------------------------------------------ */

export interface UnderstandingMetadata {
  artifactType: string;
  contractVersion: string;
  changeId: string;
  revision: number;
  status: string;
  sourcePromptRef: string;
}

export interface UnderstandingDoc {
  metadata: UnderstandingMetadata;
  sourcePrompt: string;
  intent: { objective: string; expectedOutcome: string; successIndicators: string[] };
  explicitInformation: Array<{ id: string; type: string; statement: string; sourceRef: string }>;
  inferences: Array<{
    id: string;
    statement: string;
    evidence: string;
    rationale: string;
    confidence: string;
    impactIfWrong: string;
    status: string;
  }>;
  scope: { inScope: string[]; outOfScope: Array<{ item: string; evidence: string }>; undetermined: string[] };
  ambiguities: Array<{
    id: string;
    question: string;
    interpretations: string[];
    impact: string;
    status: string;
    resolution?: string;
  }>;
  candidateRequirements: Array<{
    id: string;
    statement: string;
    origin: string;
    sourceRefs: string[];
    relatedIds?: string[];
  }>;
  summary: { narrative: string; unresolvedIssues: string[]; clarificationsNeeded: string[] };
  traceability: { sourcePromptRef: string; relatedArtifactRefs: string[]; requirementRefs: string[] };
}

/* ------------------------------------------------------------------ *
 * Escaping helpers
 * ------------------------------------------------------------------ */

/** Strip leading Markdown heading markers from each line of free text. */
export function escapeFreeText(text: string): string {
  return text
    .split(/\r?\n/)
    .map((line) => line.replace(/^\s{0,3}#{1,6}(\s|$)/, (m) => m.replace(/#/g, "")))
    .join("\n");
}

/** Single-line rendering for inline fields (newlines collapse to spaces). */
function inline(text: string): string {
  return escapeFreeText(text).replace(/\s*\n+\s*/g, " ").trim();
}

/**
 * A fenced block for untrusted content: the fence is one backtick longer
 * than the longest backtick run in the content, so the content can never
 * close its own fence.
 */
function fenced(content: string, info = "text"): string {
  const runs = content.match(/`+/g) ?? [];
  const longest = runs.reduce((m, r) => Math.max(m, r.length), 0);
  const fence = "`".repeat(Math.max(3, longest + 1));
  return `${fence}${info}\n${content.replace(/\n+$/, "")}\n${fence}`;
}

function bullets(items: string[], emptyText = "None recorded."): string {
  if (items.length === 0) return emptyText;
  return items.map((i) => `- ${inline(i)}`).join("\n");
}

/* ------------------------------------------------------------------ *
 * Renderer
 * ------------------------------------------------------------------ */

export function renderUnderstandingMarkdown(doc: UnderstandingDoc): string {
  const L: string[] = [];
  L.push(UNDERSTANDING_TITLE, "");
  L.push(
    `> Rendered by factory understanding renderer v${UNDERSTANDING_RENDERER_VERSION} from the validated \`understanding.json\`.`,
    "Do not edit this file — re-render it through the extension when the JSON changes.",
    "",
  );

  // 1. Metadata
  L.push("## 1. Metadata", "");
  L.push(`- **Change ID:** ${doc.metadata.changeId}`);
  L.push(`- **Artifact Type:** ${doc.metadata.artifactType}`);
  L.push(`- **Contract Version:** ${doc.metadata.contractVersion}`);
  L.push(`- **Renderer:** understanding-renderer v${UNDERSTANDING_RENDERER_VERSION}`);
  L.push(`- **Revision:** ${doc.metadata.revision}`);
  L.push(`- **Status:** ${doc.metadata.status}`);
  L.push(`- **Source Prompt Reference:** ${inline(doc.metadata.sourcePromptRef)}`);
  L.push("");

  // 2. Original Prompt
  L.push("## 2. Original Prompt", "");
  L.push(fenced(doc.sourcePrompt));
  L.push("");

  // 3. Interpreted Intent
  L.push("## 3. Interpreted Intent", "");
  L.push(`- **Primary Objective:** ${inline(doc.intent.objective)}`);
  L.push(`- **Expected Outcome:** ${inline(doc.intent.expectedOutcome)}`);
  L.push("- **Success Indicators:**");
  for (const s of doc.intent.successIndicators) L.push(`  - ${inline(s)}`);
  L.push("");

  // 4. Explicit Information
  L.push("## 4. Explicit Information", "");
  if (doc.explicitInformation.length === 0) {
    L.push("None recorded.");
  } else {
    for (const e of doc.explicitInformation) {
      L.push(`- **${e.id}** (${e.type}): ${inline(e.statement)} — source: ${inline(e.sourceRef)}`);
    }
  }
  L.push("");

  // 5. Inferences and Assumptions
  L.push("## 5. Inferences and Assumptions", "");
  if (doc.inferences.length === 0) {
    L.push("None recorded.");
  } else {
    for (const i of doc.inferences) {
      L.push(`### ${i.id} — ${inline(i.statement)}`, "");
      L.push(`- **Evidence:** ${inline(i.evidence)}`);
      L.push(`- **Rationale:** ${inline(i.rationale)}`);
      L.push(`- **Confidence:** ${i.confidence}`);
      L.push(`- **Status:** ${i.status}`);
      L.push(`- **Impact if wrong:** ${inline(i.impactIfWrong)}`);
      L.push("");
    }
  }

  // 6. Scope and Boundaries
  L.push("## 6. Scope and Boundaries", "");
  L.push("### In Scope", "");
  L.push(bullets(doc.scope.inScope, "(none recorded)"));
  L.push("");
  L.push("### Out of Scope", "");
  if (doc.scope.outOfScope.length === 0) {
    L.push("None recorded.");
  } else {
    for (const o of doc.scope.outOfScope) {
      L.push(`- ${inline(o.item)} — evidence: ${inline(o.evidence)}`);
    }
  }
  L.push("");
  L.push("### Undetermined", "");
  L.push(bullets(doc.scope.undetermined, "None recorded."));
  L.push("");

  // 7. Ambiguities and Open Questions
  L.push("## 7. Ambiguities and Open Questions", "");
  if (doc.ambiguities.length === 0) {
    L.push("None recorded.");
  } else {
    for (const q of doc.ambiguities) {
      L.push(`### ${q.id} [${q.status}] — ${inline(q.question)}`, "");
      L.push("- **Interpretations:**");
      for (const it of q.interpretations) L.push(`  - ${inline(it)}`);
      L.push(`- **Impact:** ${inline(q.impact)}`);
      if (q.status === "resolved" && q.resolution) L.push(`- **Resolution:** ${inline(q.resolution)}`);
      L.push("");
    }
  }

  // 8. Candidate Requirements
  L.push("## 8. Candidate Requirements", "");
  if (doc.candidateRequirements.length === 0) {
    L.push("None recorded.");
  } else {
    for (const c of doc.candidateRequirements) {
      const related = c.relatedIds && c.relatedIds.length > 0 ? ` · related: ${c.relatedIds.join(", ")}` : "";
      L.push(`- **${c.id}** (${c.origin}): ${inline(c.statement)} — sources: ${c.sourceRefs.map(inline).join(", ")}${related}`);
    }
  }
  L.push("");

  // 9. Understanding Summary
  L.push("## 9. Understanding Summary", "");
  L.push(escapeFreeText(doc.summary.narrative));
  L.push("");
  L.push("**Unresolved issues:**");
  L.push(bullets(doc.summary.unresolvedIssues, "- None recorded."));
  L.push("");
  L.push("**Clarifications needed:**");
  L.push(bullets(doc.summary.clarificationsNeeded, "- None recorded."));
  L.push("");

  // 10. Traceability
  L.push("## 10. Traceability", "");
  L.push(`- **Source prompt reference:** ${inline(doc.traceability.sourcePromptRef)}`);
  L.push(
    `- **Related artifacts:** ${
      doc.traceability.relatedArtifactRefs.length > 0
        ? doc.traceability.relatedArtifactRefs.map(inline).join("; ")
        : "(none yet)"
    }`,
  );
  L.push(
    `- **Downstream requirements:** ${
      doc.traceability.requirementRefs.length > 0
        ? doc.traceability.requirementRefs.join(", ")
        : "(not yet available)"
    }`,
  );
  L.push("");

  return L.join("\n");
}

/** Every stable local id in the document (for md↔json consistency checks). */
export function understandingIds(doc: UnderstandingDoc): string[] {
  const ids: string[] = [];
  for (const e of doc.explicitInformation) ids.push(e.id);
  for (const i of doc.inferences) ids.push(i.id);
  for (const q of doc.ambiguities) ids.push(q.id);
  for (const c of doc.candidateRequirements) ids.push(c.id);
  return ids;
}

/* ------------------------------------------------------------------ *
 * Markdown structure validation
 * ------------------------------------------------------------------ */

function isFenceToggle(line: string): boolean {
  return /^\s{0,3}(`{3,}|~{3,})/.test(line);
}

/**
 * Validate that a rendered understanding.md has the fixed structure:
 * correct title, every required heading present in the specified order
 * (fenced regions are skipped so prompt content cannot spoof headings),
 * required metadata present, and non-empty.
 */
export function validateUnderstandingMarkdown(md: string, artifactType = "understanding"): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const push = (code: string, message: string, line?: number) =>
    issues.push({
      code,
      severity: "ERROR",
      message,
      artifactType,
      rule: "structural",
      line,
    });

  if (md.trim().length === 0) {
    push("UNDERSTANDING_MD_EMPTY", "understanding.md is empty; the rendered artifact must not be.");
    return issues;
  }

  const lines = md.split(/\r?\n/);
  if (lines[0] !== UNDERSTANDING_TITLE) {
    push("UNDERSTANDING_MD_TITLE", `First line must be "${UNDERSTANDING_TITLE}", got: ${JSON.stringify(lines[0] ?? "")}`, 1);
  }

  // Locate each required heading outside fenced regions; enforce order.
  const found: number[] = []; // heading index -> 1-based line number
  let inFence = false;
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li]!;
    if (isFenceToggle(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const h = UNDERSTANDING_HEADINGS.findIndex(
      (heading, idx) => found[idx] === undefined && line === heading,
    );
    if (h >= 0) found[h] = li + 1;
  }
  for (let idx = 0; idx < UNDERSTANDING_HEADINGS.length; idx++) {
    if (found[idx] === undefined) {
      push("UNDERSTANDING_MD_HEADING_MISSING", `Required heading "${UNDERSTANDING_HEADINGS[idx]}" is missing from understanding.md.`);
      continue;
    }
    if (idx > 0 && found[idx - 1] !== undefined && found[idx]! < found[idx - 1]!) {
      push(
        "UNDERSTANDING_MD_HEADING_ORDER",
        `Heading "${UNDERSTANDING_HEADINGS[idx]}" (line ${found[idx]}) appears before "${UNDERSTANDING_HEADINGS[idx - 1]}" (line ${found[idx - 1]}); headings must keep the specified order.`,
        found[idx],
      );
    }
  }

  // Required metadata outside fences.
  inFence = false;
  const body: string[] = [];
  for (const line of lines) {
    if (isFenceToggle(line)) {
      inFence = !inFence;
      continue;
    }
    if (!inFence) body.push(line);
  }
  const bodyText = body.join("\n");
  if (!/- \*\*Change ID:\*\* \S+/.test(bodyText)) {
    push("UNDERSTANDING_MD_METADATA", "Required metadata '- **Change ID:** …' is missing from the Metadata section.");
  }
  if (!/- \*\*Artifact Type:\*\* understanding/.test(bodyText)) {
    push("UNDERSTANDING_MD_METADATA", "Required metadata '- **Artifact Type:** understanding' is missing.");
  }
  if (!/- \*\*Status:\*\* \S+/.test(bodyText)) {
    push("UNDERSTANDING_MD_METADATA", "Required metadata '- **Status:** …' is missing.");
  }

  return issues;
}
