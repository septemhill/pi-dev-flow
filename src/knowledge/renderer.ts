import {
  KNOWLEDGE_TYPE_LABEL,
  type ConstraintDoc,
  type ConventionDoc,
  type KnowledgeDoc,
  type KnowledgeType,
  type TechDecisionDoc,
} from "./types.ts";

/**
 * Deterministic Markdown renderer for Project Knowledge.
 *
 * Invariant: Markdown = Render(Validated JSON, RENDERER_VERSION).
 * The renderer accepts only documents that already passed schema + semantic
 * validation, uses a fixed heading/field order, renders every non-empty
 * canonical field, and produces byte-identical output for equivalent input.
 * It never invents content.
 */
export const RENDERER_VERSION = "1.0.0";

export function renderKnowledgeMarkdown(type: KnowledgeType, doc: KnowledgeDoc): string {
  switch (type) {
    case "constraint":
      return renderConstraint(doc as ConstraintDoc);
    case "convention":
      return renderConvention(doc as ConventionDoc);
    case "tech-decision":
      return renderTechDecision(doc as TechDecisionDoc);
  }
}

function scopeText(scope: { level: string; paths: string[] }): string {
  return scope.level === "project" ? "project (entire repository)" : `${scope.level}: ${scope.paths.join(", ")}`;
}

function header(type: KnowledgeType, id: string, title: string, status: string, scope: { level: string; paths: string[] }): string[] {
  return [
    `<!-- Generated by pi-ai-factory knowledge renderer v${RENDERER_VERSION} from ${id}.json.`,
    `     Do not edit this file by hand: edit the canonical JSON and re-render. -->`,
    "",
    `# ${KNOWLEDGE_TYPE_LABEL[type]} ${id}: ${title}`,
    "",
    `- **Status:** ${status}`,
    `- **Scope:** ${scopeText(scope)}`,
    "",
  ];
}

function codeBlock(code: string): string {
  // Deterministic fence: longer than any backtick run in the content.
  const longest = (code.match(/`+/g) ?? [""]).reduce((m, run) => Math.max(m, run.length), 0);
  const fence = "`".repeat(Math.max(3, longest + 1));
  return `${fence}\n${code.replace(/\n$/, "")}\n${fence}`;
}

function renderConstraint(doc: ConstraintDoc): string {
  const lines: string[] = [
    ...header("constraint", doc.id, doc.title, doc.status, doc.scope),
    `## Description`,
    "",
    doc.description,
    "",
    `## Rule`,
    "",
    doc.rule,
    "",
    `## Severity`,
    "",
    doc.severity,
    "",
    `## Verification`,
    "",
    `- **Method:** ${doc.verification.method}`,
    `- **Validator:** ${doc.verification.validator ?? "none"}`,
    "",
    `### Verification instructions`,
    "",
    doc.verification.instructions,
    "",
  ];
  return lines.join("\n");
}

function renderConvention(doc: ConventionDoc): string {
  const lines: string[] = [
    ...header("convention", doc.id, doc.title, doc.status, doc.scope),
    `## Description`,
    "",
    doc.description,
    "",
    `## Practice`,
    "",
    doc.practice,
    "",
    `## Rationale`,
    "",
    doc.rationale,
    "",
    `## Enforcement`,
    "",
    doc.enforcement,
    "",
    `## Verification instructions`,
    "",
    doc.verification_instructions,
    "",
    `## Examples`,
    "",
  ];
  if (doc.examples.length === 0) {
    lines.push("None documented.");
  } else {
    for (const ex of doc.examples) {
      lines.push(`### Example (${ex.kind})`);
      lines.push("");
      lines.push(ex.description);
      lines.push("");
      lines.push(codeBlock(ex.code));
      lines.push("");
    }
  }
  return lines.join("\n");
}

function renderTechDecision(doc: TechDecisionDoc): string {
  const lines: string[] = [
    ...header("tech-decision", doc.id, doc.title, doc.status, doc.scope),
    `## Context`,
    "",
    doc.context,
    "",
    `## Decision`,
    "",
    doc.decision,
    "",
    `## Rationale`,
    "",
    doc.rationale,
    "",
    `## Alternatives considered`,
    "",
  ];
  if (doc.alternatives.length === 0) {
    lines.push("None documented.");
  } else {
    for (const a of doc.alternatives) {
      lines.push(`- **${a.option}** — ${a.reason_not_selected}`);
    }
  }
  lines.push("", `## Consequences`, "");
  if (doc.consequences.length === 0) {
    lines.push("None documented.");
  } else {
    for (const c of doc.consequences) lines.push(`- ${c}`);
  }
  lines.push("", `## Supersedes`, "", doc.supersedes ?? "None", "");
  return lines.join("\n");
}
