import { describe, expect, it } from "vitest";
import { renderKnowledgeMarkdown, RENDERER_VERSION } from "../src/knowledge/renderer.ts";
import { baseConstraint, baseConvention, baseDecision } from "./knowledge-fixtures.ts";

describe("knowledge renderer: deterministic output", () => {
  it("renders the same document identically (Markdown = Render(JSON, version))", () => {
    expect(renderKnowledgeMarkdown("constraint", baseConstraint())).toBe(renderKnowledgeMarkdown("constraint", baseConstraint()));
    expect(renderKnowledgeMarkdown("convention", baseConvention())).toBe(renderKnowledgeMarkdown("convention", baseConvention()));
    expect(renderKnowledgeMarkdown("tech-decision", baseDecision())).toBe(renderKnowledgeMarkdown("tech-decision", baseDecision()));
  });

  it("includes the renderer version and the source file, and warns against hand edits", () => {
    const md = renderKnowledgeMarkdown("constraint", baseConstraint());
    expect(md).toContain(`renderer v${RENDERER_VERSION}`);
    expect(md).toContain("from CON-001.json");
    expect(md).toContain("Do not edit this file by hand");
  });

  it("changes when the document changes", () => {
    const base = renderKnowledgeMarkdown("constraint", baseConstraint());
    const modified = renderKnowledgeMarkdown("constraint", baseConstraint({ rule: "A completely different rule." }));
    expect(modified).not.toBe(base);
    expect(modified).toContain("A completely different rule.");
  });

  it("renders all constraint fields", () => {
    const md = renderKnowledgeMarkdown(
      "constraint",
      baseConstraint({ verification: { method: "automated", validator: "tests/security.test.ts", instructions: "run it" }, severity: "warning" }),
    );
    for (const expected of [
      "# Constraint CON-001: No credentials in logs",
      "- **Status:** draft",
      "## Description",
      "Credential material must never reach application log output.",
      "## Rule",
      "Credential material must never be written to application logs.",
      "## Severity",
      "warning",
      "## Verification",
      "- **Method:** automated",
      "- **Validator:** tests/security.test.ts",
      "### Verification instructions",
      "run it",
    ]) {
      expect(md).toContain(expected);
    }
  });

  it("renders scope: project vs narrowed paths", () => {
    expect(renderKnowledgeMarkdown("constraint", baseConstraint({ scope: { level: "module", paths: ["src/api/**"] } }))).toContain("- **Scope:** module: src/api/**");
    expect(renderKnowledgeMarkdown("constraint", baseConstraint())).toContain("- **Scope:** project (entire repository)");
  });

  it("renders convention examples and the empty-case marker", () => {
    const md = renderKnowledgeMarkdown("convention", baseConvention());
    expect(md).toContain("## Examples");
    expect(md).toContain("### Example (positive)");
    expect(md).toContain("### Example (negative)");
    expect(md).toContain("```");
    expect(md).toContain("log.info('req done', { ms })");
    const none = renderKnowledgeMarkdown("convention", baseConvention({ examples: [] }));
    expect(none).toContain("None documented.");
  });

  it("renders tech decision sections including empty alternatives/consequences", () => {
    const md = renderKnowledgeMarkdown("tech-decision", baseDecision({ alternatives: [], consequences: [] }));
    expect(md).toContain("## Context");
    expect(md).toContain("## Decision");
    expect(md).toContain("## Rationale");
    expect(md).toContain("## Alternatives considered");
    expect(md).toContain("None documented.");
    expect(md).toContain("## Consequences");
    expect(md).toContain("## Supersedes");
    expect(md).toContain("None");

    const full = renderKnowledgeMarkdown("tech-decision", baseDecision({ supersedes: "ADR-000" }));
    expect(full).toContain("- **SQLite** — No concurrent write support for the service tier.");
    expect(full).toContain("ADR-000");
  });

  it("renders terminal statuses verbatim", () => {
    expect(renderKnowledgeMarkdown("constraint", baseConstraint({ status: "deprecated" as never }))).toContain("- **Status:** deprecated");
    expect(renderKnowledgeMarkdown("tech-decision", baseDecision({ status: "accepted" as never }))).toContain("- **Status:** accepted");
  });

  it("fences code containing backticks with a longer fence", () => {
    const doc = baseConvention({ examples: [{ kind: "positive", description: "d", code: 'x = "``"; print(x)' }] });
    const md = renderKnowledgeMarkdown("convention", doc);
    expect(md).toContain('x = "``"; print(x)');
    // the content line is not swallowed into a fence of the same length
    expect(md.split("\n").filter((l) => l === "```").length).toBe(2);
  });

  it("is stable across calls (no timestamps/randomness)", () => {
    expect(renderKnowledgeMarkdown("tech-decision", baseDecision())).toBe(renderKnowledgeMarkdown("tech-decision", baseDecision()));
  });
});
